import os
from dotenv import load_dotenv
from google import genai

# .envを読み込む
load_dotenv()

# 環境変数からAPIキーを取得
api_key = os.getenv("GEMINI_API_KEY")

if api_key is None:
    raise ValueError(
        "GEMINI_API_KEY が読み込めていません。.env ファイルを確認してください。"
    )


client = genai.Client(api_key=api_key)

prompt = """
以下の例を参考に、最後の問題の解答を導き出してください。

例題1:
日本の近代化に関連するできごとについて述べた次のア～ウを年代の古い順に正しく並べよ。

ア　府知事・県令からなる地方官会議が設置された。
イ　廃藩置県が実施され，中央から府知事・県令が派遣される体制になった。
ウ　すべての藩主が，天皇に領地と領民を返還した。

解答: ウ→イ→ア

例題2:
江戸幕府の北方での対外的な緊張について述べた次の文ア～ウを年代の古い順に正しく並べよ。

ア　レザノフが長崎に来航したが，幕府が冷淡な対応をしたため，ロシア船が樺太や択捉島を攻撃した。
イ　ゴローウニンが国後島に上陸し，幕府の役人に捕らえられ抑留された。
ウ　ラクスマンが根室に来航し，漂流民を届けるとともに通商を求めた。

解答: ウ→ア→イ

例題3:
中居屋重兵衛の生涯の期間におこったできごとについて述べた次のア～ウを，年代の古い順に正しく並べよ。

ア　アヘン戦争がおこり，清がイギリスに敗北した。
イ　異国船打払令が出され，外国船を撃退することが命じられた。
ウ　桜田門外の変がおこり，大老の井伊直弼が暗殺された。

解答: イ→ア→ウ

例題4:
加藤高明が外務大臣として提言を行ってから、内閣総理大臣となり演説を行うまでの時期のできごとについて述べた次のア～ウを，年代の古い順に正しく並べよ。

ア　朝鮮半島において，独立を求める大衆運動である三・一独立運動が展開された。
イ　関東大震災後の混乱のなかで，朝鮮人や中国人に対する殺傷事件がおきた。
ウ　日本政府が，袁世凱政府に対して二十一カ条の要求を突き付けた。

解答: ウ→ア→イ

問題:
9世紀に活躍した人物に関係するできごとについて述べた次のア～ウを年代の古い順に正しく並べよ。

ア　藤原時平は，策謀を用いて菅原道真を政界から追放した。
イ　嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。
ウ　藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。

上記の例を参考に、この問題の解答を示してください。具体的な年代とともに説明を加えてください。
"""

response = client.models.generate_content(
    model="gemini-2.5-flash",
    contents=prompt,
)

# 結果の表示
print(response.text)

# 出力
# 解答: イ→ウ→ア

# 具体的な年代と説明は以下の通りです。

# *   **イ　嵯峨天皇は，藤原冬嗣らを蔵人頭に任命した。**
#     *   **年代:** 弘仁元年（810年）
#     *   **説明:** 薬子の変（平城太上天皇の変）の後、嵯峨天皇が自らの秘書官・側近として新設した令外官が蔵人頭です。これによって天皇の権力強化が図られ、藤原冬嗣がその初代の筆頭蔵人頭に就任したことで、藤原北家が台頭する重要なきっかけとなりました。

# *   **ウ　藤原良房は，承和の変後，藤原氏の中での北家の優位を確立した。**
#     *   **年代:** 承和9年（842年）
#     *   **説明:** 淳和上皇の崩御後、皇位継承をめぐる政争（恒貞親王と道康親王）が発生しました。この際、藤原良房は謀略を用いて恒貞親王を廃し、道康親王（後の文徳天皇）を擁立することに成功しました。この事件を通じて良房は太政官の首班としての地位を不動のものとし、藤原北家が他の藤原氏諸家（南家、式家、京家）を圧倒して、後の摂関政治へと繋がる基盤を確立しました。

# *   **ア　藤原時平は，策謀を用いて菅原道真を政界から追放した。**
#     *   **年代:** 昌泰4年（901年）
#     *   **説明:** 宇多上皇の信任を得て太政官で権勢を振るっていた菅原道真に対し、藤原時平が醍醐天皇に讒言し、道真を大宰府に左遷させた事件です（昌泰の変）。これは厳密には10世紀初頭の出来事ですが、藤原時平が9世紀後半から活躍し、他氏排斥を進める中で起こった、藤原氏による摂関政治確立の重要な段階を示す出来事です。
