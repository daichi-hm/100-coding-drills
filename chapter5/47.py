import os
import time
from dotenv import load_dotenv
from google import genai
from google.genai import types
from google.genai import errors

# ==============================
# 設定
# ==============================

# 使用するモデル
MODEL_NAME = "gemini-2.5-flash"


# ==============================
# APIキーの読み込み
# ==============================

# .env ファイルを読み込む
load_dotenv()

# 環境変数から Gemini API キーを取得する
api_key = os.getenv("GEMINI_API_KEY")

# APIキーが読み込めなかった場合はエラーを出す
if api_key is None:
    raise ValueError(
        "GEMINI_API_KEY が読み込めていません。.env ファイルを確認してください。"
    )

# Gemini API のクライアントを作成する
client = genai.Client(api_key=api_key)


# ==============================
# 46番で生成した川柳
# ==============================

# ここには、46番で実際に生成された川柳を入れる
# 今回は例として「研究室生活」をお題にした川柳を入れている
senryu_list = [
    "徹夜明け コーヒー片手に 夢うつつ",
    "データ出ず 頭抱える 夜が更ける",
    "教授室 ドア開く音に 背筋伸び",
    "論文を 眺め五月雨 過ぎていく",
    "実験は 失敗重ねて 進む道",
    "パソコンと 語らい迎える 朝日かな",
    "締め切り前 仲間と食べる カップ麺",
    "白衣着て 今日もフラスコ 振る一日",
    "進捗は 聞かれるたびに 汗をかく",
    "卒業の 夢見て今日も キーを打つ",
]


# ==============================
# 評価用プロンプトを作る
# ==============================


def make_evaluation_prompt(senryu_list):
    """
    川柳リストを受け取り、LLMに評価させるためのプロンプトを作る関数。
    """

    # 川柳を番号付きの文字列にする
    senryu_text = ""

    for i, senryu in enumerate(senryu_list, start=1):
        senryu_text += f"{i}. {senryu}\n"

    # LLMに評価基準と出力形式を指定する
    prompt = f"""
以下の川柳の面白さを10段階で評価してください。

評価基準:
- 1点: ほとんど面白くない
- 5点: 普通
- 10点: とても面白い
- 共感しやすさ、意外性、言葉のうまさ、オチの良さを総合的に見て評価してください。

出力形式:
番号: 点数 - 簡単な理由

例:
1: 8 - 研究室生活の焦りがよく出ていて共感しやすい。

川柳:
{senryu_text}
"""
    return prompt


# ==============================
# Geminiに問い合わせる関数
# ==============================


def ask_gemini(prompt, max_retries=5):
    """
    Gemini APIに問い合わせる関数。
    503や429などの一時的なエラーが出た場合は、少し待って再試行する。
    """

    for i in range(max_retries):
        try:
            # Gemini APIにプロンプトを送って、応答を生成させる
            response = client.models.generate_content(
                model=MODEL_NAME,
                contents=prompt,
                config=types.GenerateContentConfig(
                    # 評価タスクなので、なるべく評価がぶれないように低めにする
                    temperature=0,
                    # 10個分の評価理由を書くため、少し余裕を持たせる
                    max_output_tokens=4096,
                ),
            )

            # Geminiの応答テキストを返す
            return response.text

        except errors.ServerError as e:
            # 503 UNAVAILABLE など、Gemini側の混雑エラー
            print(f"サーバーエラーが起きました。{i + 1}回目のリトライをします。")
            print(e)

            # 10秒、20秒、30秒... と少しずつ長く待つ
            time.sleep(10 * (i + 1))

        except errors.ClientError as e:
            # 429 RESOURCE_EXHAUSTED など、レート制限エラー
            print(f"クライアントエラーが起きました。{i + 1}回目のリトライをします。")
            print(e)

            if "429" in str(e) or "RESOURCE_EXHAUSTED" in str(e):
                print("レート制限に達したため、60秒待機します。")
                time.sleep(60)
            else:
                # 429以外のクライアントエラーは、APIキーなど別原因の可能性があるので止める
                raise

    # 指定回数リトライしても失敗した場合
    return "エラーにより評価を生成できませんでした。"


# ==============================
# 実行
# ==============================

prompt = make_evaluation_prompt(senryu_list)

evaluation = ask_gemini(prompt)

print("===== 川柳の評価結果 =====")
print(evaluation)

